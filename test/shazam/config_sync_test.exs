      Enum.each(["project", "rules", "decisions", "agents"], fn dir ->
        File.mkdir_p!(Path.join(memories_base, dir))
      end)

      # Project memory
      File.write!(Path.join(memories_base, "project/overview.md"), """
      ---
      name: overview
      description: Project overview
      tags: project
      ---

      This is an Elixir/Phoenix web app for managing condos.
      """)

