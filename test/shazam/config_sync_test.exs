      ClaudeGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)
      settings_path = Path.join(ws, ".claude/settings.json")
      assert File.exists?(settings_path)
      # Overwrite with custom content (no Shazam header)
      File.write!(settings_path, "{\"custom\": true}")
      # Re-generate
      files = ClaudeGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)
      # settings.json should not be in the file list since it already exists
      settings_file = Enum.find(files, &(&1.type == "settings"))
      assert settings_file == nil
