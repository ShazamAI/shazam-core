  describe "ConfigSync.status/1" do
    test "reports no files when workspace is empty", %{workspace: ws} do
      status = Shazam.ConfigSync.status(ws)
      assert status.workspace == ws
      assert status.count == 0
      assert status.synced_files == []
    end

    test "detects generated files", %{workspace: ws, agents: agents} do
      ClaudeGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)
      CodexGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)

      status = Shazam.ConfigSync.status(ws)
      assert status.count > 0

      providers = Enum.map(status.synced_files, & &1.provider)
      assert "claude" in providers
      assert "codex" in providers
    end

    test "detects last sync time from CLAUDE.md", %{workspace: ws, agents: agents} do
      ClaudeGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)
