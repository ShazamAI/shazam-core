      # First generate files
      ClaudeGenerator.generate(ws, agents, [], "Test", %{}, %{}, false)
      # Manually overwrite a file without the Shazam header
      claude_md_path = Path.join(ws, "CLAUDE.md")
      File.write!(claude_md_path, "# My custom CLAUDE.md\nDo not overwrite me.")
      # Re-generate — should NOT overwrite
      ClaudeGenerator.generate(ws, agents, [], "Test v2", %{}, %{}, false)
      content = File.read!(claude_md_path)
      assert String.contains?(content, "My custom CLAUDE.md")
      refute String.contains?(content, "Test v2")
    end

